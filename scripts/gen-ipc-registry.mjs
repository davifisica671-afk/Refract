#!/usr/bin/env node
/**
 * gen-ipc-registry.mjs — generates the canonical IPC channel registry.
 *
 * Reads the actual channel usage from the Electron sources via the shared
 * scanner (electron/ipc/ipcScan.mjs) and writes electron/ipc/ipcChannels.mjs
 * as the single source of truth for every IPC channel: its name, kind,
 * category, and where it is wired in the main process.
 *
 * Run after adding/removing/renaming a channel:
 *     node scripts/gen-ipc-registry.mjs
 *
 * The companion test (electron/services/__tests__/IpcChannelRegistry.test.mjs)
 * re-scans the sources with the same scanner and fails if the committed
 * registry drifts from the code, in either direction.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanIpcSurface, buildRegistryRecords } from '../electron/ipc/ipcScan.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outPath = path.join(root, 'electron/ipc/ipcChannels.mjs');

const surface = scanIpcSurface();
const coreRecords = buildRegistryRecords(surface);

// ---------------------------------------------------------------------------
// Category bucketing (informational grouping by channel prefix)
// ---------------------------------------------------------------------------
const CATEGORY_PREFIXES = [
  ['agent:', 'agent'],
  ['browser-context:', 'browser-context'],
  ['calendar-', 'calendar'],
  ['code:', 'code-assistant'],
  ['code-', 'code-assistant'],
  ['cropper-', 'cropper'],
  ['diagram:', 'diagram'],
  ['dialog:', 'dialog'],
  ['dev:', 'dev'],
  ['dynamic-action:', 'dynamic-actions'],
  ['embedding:', 'embeddings'],
  ['git:', 'git'],
  ['hindsight-config:', 'hindsight'],
  ['intelligence-', 'intelligence'],
  ['interface-theme:', 'theme'],
  ['keybinds:', 'keybinds'],
  ['language-learning:', 'language-learning'],
  ['lecture:', 'lecture'],
  ['lemonsqueezy:', 'licensing'],
  ['license:', 'licensing'],
  ['local-whisper-', 'local-whisper'],
  ['mode-', 'modes'],
  ['modes:', 'modes'],
  ['model-', 'models'],
  ['purchase-activation:', 'licensing'],
  ['rag:', 'rag'],
  ['repo-index:', 'repo-indexer'],
  ['role-twin:', 'role-twin'],
  ['stealth-tap:', 'stealth'],
  ['purchase-', 'licensing'],
];

function categorize(name) {
  for (const [prefix, cat] of CATEGORY_PREFIXES) {
    if (name.startsWith(prefix)) return cat;
  }
  return 'misc';
}

// ---------------------------------------------------------------------------
// Add informational category metadata on top of the core records
// ---------------------------------------------------------------------------
const records = coreRecords.map(r => ({ ...r, category: categorize(r.name) }));

// ---------------------------------------------------------------------------
// Emit
// ---------------------------------------------------------------------------
const header = `// AUTO-GENERATED by scripts/gen-ipc-registry.mjs — do not edit by hand.
// Canonical inventory of every IPC channel in the Electron app: its name,
// kind (renderer perspective), category, and where it is wired in the main
// process. Regenerate after adding/removing/renaming a channel:
//     node scripts/gen-ipc-registry.mjs
//
// kind:
//   'invoke' — renderer ipcRenderer.invoke(name)  -> main safeHandle/ipcMain.handle
//   'send'   — renderer ipcRenderer.send(name)     -> main safeOn/ipcMain.on
//   'event'  — main .send(name)                    -> renderer ipcRenderer.on(name)
//
// handlers: main-process files that register the handler/listener (relative to repo root).
// senders:  main-process files that .send() the event (best-effort).
// orphan:   registered in main but no matching renderer caller (dead code to review).
`;

const body = records
  .map(r => {
    const fields = [];
    fields.push(`name: ${JSON.stringify(r.name)}`);
    fields.push(`kind: ${JSON.stringify(r.kind)}`);
    fields.push(`category: ${JSON.stringify(r.category)}`);
    fields.push(`handlers: ${JSON.stringify(r.handlers)}`);
    fields.push(`senders: ${JSON.stringify(r.senders)}`);
    if (r.orphan) fields.push('orphan: true');
    return `  { ${fields.join(', ')} },`;
  })
  .join('\n');

const output = `${header}\nexport const IPC_CHANNELS = Object.freeze([\n${body}\n]);\n`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output);

// ---------------------------------------------------------------------------
// Emit the compile-time type contracts (electron/ipc/ipcChannels.ts)
// ---------------------------------------------------------------------------
const tsPath = path.join(root, 'electron/ipc/ipcChannels.ts');
const union = kind =>
  records
    .filter(r => r.kind === kind)
    .map(r => r.name)
    .sort()
    .map(name => `  | ${JSON.stringify(name)}`)
    .join('\n');

const tsHeader = `// AUTO-GENERATED by scripts/gen-ipc-registry.mjs — do not edit by hand.
// Compile-time IPC channel contracts, generated from the same scan as
// ipcChannels.mjs. Type the safeHandle / safeOn / registerStealthHandler
// wrappers with these unions so a typo'd channel name becomes a compile
// error instead of a silent runtime miss.
//
// Regenerate with: node scripts/gen-ipc-registry.mjs

export type IpcChannelKind = 'invoke' | 'send' | 'event';

export type IpcInvokeChannel =\n${union('invoke')};\n

export type IpcSendChannel =\n${union('send')};\n

export type IpcEventChannel =\n${union('event')};\n

export type IpcChannel = IpcInvokeChannel | IpcSendChannel | IpcEventChannel;\n`;

fs.writeFileSync(tsPath, tsHeader);

console.log(`Wrote electron/ipc/ipcChannels.ts — type contracts for ${records.length} channels`);

console.log(`Wrote electron/ipc/ipcChannels.mjs — ${records.length} channels`);
console.log(`  invoke: ${records.filter(r => r.kind === 'invoke').length}`);
console.log(`  send:   ${records.filter(r => r.kind === 'send').length}`);
console.log(`  event:  ${records.filter(r => r.kind === 'event').length}`);
console.log(`  orphan: ${records.filter(r => r.orphan).length}`);
console.log(`  invoke with NO handler: ${records.filter(r => r.kind === 'invoke' && r.handlers.length === 0).map(r => r.name).join(', ') || '(none)'}`);
